import { createHash } from 'node:crypto'
import { readdirSync, statSync } from 'node:fs'
import path from 'node:path'
import type { Plugin } from 'vite'

const CACHE_PREFIX = 'hsp-offline-'

/** Service worker source: precache every build file, cache-first assets, offline SPA navigation. */
export function renderServiceWorker(version: string, urls: string[], base: string): string {
  return `// Generated by scripts/bundling/offlineCache.ts — do not edit.
const CACHE = ${JSON.stringify(CACHE_PREFIX + version)}
const PRECACHE = ${JSON.stringify(urls)}
const SHELL = ${JSON.stringify(base + 'index.html')}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith(${JSON.stringify(CACHE_PREFIX)}) && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return
  if (request.mode === 'navigate') {
    // Network first so a new deployment shows up; any scene URL falls back to the cached shell offline.
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok) caches.open(CACHE).then((cache) => cache.put(SHELL, response.clone()))
          return response
        })
        .catch(() => caches.match(SHELL, { ignoreVary: true })),
    )
    return
  }
  // ignoreVary: the precached entries were fetched without the Origin header that crossorigin
  // module scripts send, and servers commonly answer with Vary: Origin / Accept-Encoding.
  event.respondWith(
    caches.match(request, { ignoreVary: true }).then((hit) =>
      hit ||
      fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone()
          caches.open(CACHE).then((cache) => cache.put(request, copy))
        }
        return response
      }),
    ),
  )
})
`
}

function listFiles(dir: string, root = dir): string[] {
  let files: string[] = []
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name)
    if (statSync(full).isDirectory()) files = files.concat(listFiles(full, root))
    else files.push(path.relative(root, full).split(path.sep).join('/'))
  }
  return files
}

/** URLs to precache: the shell, every emitted file (minus source maps) and the public folder. */
export function collectPrecacheUrls(bundleFiles: string[], publicFiles: string[], base: string): string[] {
  const files = [...bundleFiles, ...publicFiles].filter((file) => !file.endsWith('.map') && file !== 'sw.js')
  return [base, ...new Set(files.map((file) => base + file))].sort()
}

/**
 * Emits sw.js so a classroom that opened the site once keeps working without a network: the
 * whole build (~2.5 MB: every scene, three.js, thumbnails) is cached on first visit.
 */
export function offlineCache(): Plugin {
  let base = '/'
  let publicDir = ''
  return {
    name: 'offline-cache',
    apply: 'build',
    enforce: 'post',
    configResolved(config) {
      base = config.base
      publicDir = config.publicDir
    },
    generateBundle(_options, bundle) {
      const publicFiles = publicDir ? listFiles(publicDir) : []
      const urls = collectPrecacheUrls(Object.keys(bundle), publicFiles, base)
      const version = createHash('sha256').update(urls.join('\n')).digest('hex').slice(0, 12)
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: renderServiceWorker(version, urls, base) })
    },
  }
}
